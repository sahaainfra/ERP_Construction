// Generates src/design/tokens.css from design/design-tokens.json (DS-4, DS-5, DS-9).
// Run with: node scripts/build-tokens.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const tokens = JSON.parse(readFileSync(join(root, "design/design-tokens.json"), "utf8"));

const THEMES = ["light", "dark", "high-contrast"];

// Flattens a nested token object into [name, { light, dark, "high-contrast" }] pairs.
function flattenColours(node, prefix = []) {
  const out = [];
  for (const [key, value] of Object.entries(node)) {
    const path = [...prefix, key];
    if (value && typeof value === "object" && !("light" in value)) {
      out.push(...flattenColours(value, path));
    } else {
      out.push([path.join("-"), value]);
    }
  }
  return out;
}

const colours = flattenColours(tokens.color).map(([name, values]) => [`--erp-color-${name}`, values]);
// Status roles expose fg / bg / solid; the flatten above already yields e.g. --erp-color-status-success-fg.

function block(selector, lines) {
  return `${selector} {\n${lines.map((l) => `  ${l}`).join("\n")}\n}\n`;
}

function colourLines(theme) {
  return colours.map(([name, values]) => `${name}: ${values[theme]};`);
}

const chartLines = (theme) =>
  tokens.chart.categorical[theme === "high-contrast" ? "light" : theme].map((hex, i) => `--erp-chart-${i + 1}: ${hex};`);

const structural = [
  ...Object.entries(tokens.space).map(([k, v]) => `--erp-space-${k}: ${v}px;`),
  ...Object.entries(tokens.radius).map(([k, v]) => `--erp-radius-${k}: ${v === 999 ? "999px" : `${v}px`};`),
  ...Object.entries(tokens.elevation).map(([k, v]) => `--erp-elevation-${k}: ${v};`),
  ...Object.entries(tokens.breakpoints).map(([k, v]) => `--erp-breakpoint-${k}: ${v}px;`),
  ...Object.entries(tokens.zIndex).map(([k, v]) => `--erp-z-${k}: ${v};`),
  ...Object.entries(tokens.motion.durationMs).map(([k, v]) => `--erp-duration-${k}: ${v}ms;`),
  `--erp-easing-standard: ${tokens.motion.easing};`,
  `--erp-shell-bar-height: ${tokens.layout.shellBarPx}px;`,
  `--erp-side-nav-width: ${tokens.layout.sideNavPx}px;`,
  `--erp-rail-width: ${tokens.layout.railPx}px;`,
  `--erp-grid-gutter: ${tokens.layout.dashboardGrid.gutterPx}px;`,
  `--erp-grid-row-unit: ${tokens.layout.dashboardGrid.rowUnitPx}px;`,
  `--erp-font-ui: "IBM Plex Sans", "Noto Sans", system-ui, sans-serif;`,
  `--erp-font-mono: "IBM Plex Mono", ui-monospace, monospace;`,
];

const typeLines = Object.entries(tokens.typography.styles).flatMap(([name, s]) => [
  `--erp-type-${name}-size: ${s.size}px;`,
  `--erp-type-${name}-line: ${s.lineHeight}px;`,
  `--erp-type-${name}-weight: ${s.weight};`,
]);

const densityLines = (mode) => {
  const d = tokens.density[mode];
  return [`--erp-control-height: ${d.controlPx}px;`, `--erp-row-height: ${d.rowPx}px;`, `--erp-icon-size: ${d.iconPx}px;`];
};

// Dark follows the OS preference only while the user has not chosen a theme.
const darkSelector = ':root:not([data-theme="light"]):not([data-theme="high-contrast"])';

const indent = (text) => text.replace(/^/gm, "  ");

let css = `/* GENERATED by scripts/build-tokens.mjs from design/design-tokens.json. Do not edit by hand. */\n\n`;
css += block(":root", [...structural, ...typeLines, ...colourLines("light"), ...chartLines("light"), ...densityLines("cozy")]);
css += `\n@media (prefers-color-scheme: dark) {\n`;
css += indent(block(darkSelector, [...colourLines("dark"), ...chartLines("dark")]));
css += `}\n\n`;
css += block(':root[data-theme="dark"]', [...colourLines("dark"), ...chartLines("dark")]);
css += `\n`;
css += block(':root[data-theme="high-contrast"]', [...colourLines("high-contrast"), ...chartLines("high-contrast")]);
css += `\n`;
for (const mode of ["compact", "cozy", "touch"]) {
  css += block(`:root[data-density="${mode}"]`, densityLines(mode));
}

writeFileSync(join(root, "src/design/tokens.css"), css);
console.log(`Wrote src/design/tokens.css (${THEMES.length} themes, ${colours.length} colour tokens)`);
