// Generates src/program/legacy.generated.json from docs/program/annex-d-legacy-mapping.md (Part 00 Annex D).
// Run with: node scripts/build-legacy-crosswalk.mjs
// Fails on malformed rows so the crosswalk cannot drift silently.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const markdown = readFileSync(join(root, "docs/program/annex-d-legacy-mapping.md"), "utf8");

// Rows of the first table after a "## <heading>" line, with the expected cell count.
function tableRows(heading, cellCount) {
  const lines = markdown.split("\n");
  const start = lines.findIndex((l) => l.startsWith(heading));
  if (start < 0) throw new Error(`Heading not found: ${heading}`);
  const rows = [];
  let header = false;
  for (let i = start + 1; i < lines.length; i++) {
    const line = lines[i];
    if (line.startsWith("## ")) break;
    if (!line.startsWith("|")) {
      if (header) break; // a table has ended
      continue;
    }
    if (!header) {
      header = true; // header row
      continue;
    }
    if (/^\|\s*-+/.test(line)) continue;
    const cells = line.slice(1, -1).split("|").map((c) => c.trim());
    if (cells.length !== cellCount) throw new Error(`${heading} line ${i + 1}: expected ${cellCount} cells, got ${cells.length}`);
    rows.push(cells);
  }
  return rows;
}

const PART = /^\d{2}[A-C]?$/;
const ids = (text) => [...text.matchAll(/\b(\d{2}[A-C]?)\b/g)].map((m) => m[1]);
const unticked = (text) => text.replace(/`/g, "").trim();

// D2: VERIFY & EXTEND Parts
const verifyExtend = tableRows("## D2", 4).map(([part, title, legacyBuilt, stillToBuild]) => {
  if (!PART.test(part)) throw new Error(`D2 bad Part ${part}`);
  return {
    part,
    title,
    legacyBuiltPrompts: legacyBuilt === "—" ? [] : legacyBuilt.split(",").map((s) => s.trim()),
    stillToBuildPrompts: stillToBuild === "—" ? [] : stillToBuild.split(",").map((s) => s.trim()),
  };
});

// D3: consolidations
const consolidations = tableRows("## D3", 3).map(([part, title, merged]) => {
  if (!PART.test(part)) throw new Error(`D3 bad Part ${part}`);
  return { part, title, oldPrompts: merged.split(",").map((s) => s.trim()) };
});

// D4: aliases. Legacy codes are kept verbatim, including forms such as perf(P131).
const aliases = tableRows("## D4", 3).map(([partCell, moduleCode, legacy]) => {
  const part = partCell.replace(/^Part\s+/, "");
  if (!PART.test(part)) throw new Error(`D4 bad Part ${partCell}`);
  return {
    part,
    moduleCode: unticked(moduleCode),
    legacyCodes: legacy.split(/,\s*(?![^()]*\))/).map((c) => unticked(c)).filter(Boolean),
  };
});

// D5: full crosswalk, old prompt to new Part(s)
const crosswalk = tableRows("## D5", 5).map(([oldPrompt, oldTitle, formerId, legacyBuilt, newParts]) => {
  const newPartIds = newParts.split(",").map((s) => s.trim().replace(/^Part\s+/, ""));
  for (const p of newPartIds) if (!PART.test(p)) throw new Error(`D5 prompt ${oldPrompt}: bad Part ${p}`);
  return {
    oldPrompt,
    oldTitle,
    formerId: unticked(formerId) || null,
    legacyBuilt: legacyBuilt === "✔",
    newParts: newPartIds,
  };
});

// D6 and D7: uploaded module crosswalks. Their "Now in" cells mix IDs with text, so IDs are extracted.
const moduleCrosswalk = (heading) =>
  tableRows(heading, 4).map(([modulePart, title, nowIn, notes]) => ({
    modulePart,
    title,
    nowInParts: ids(nowIn),
    nowInText: nowIn,
    notes,
  }));
const plantModule = moduleCrosswalk("## D6");
const workchatModule = moduleCrosswalk("## D7");

const out = {
  source: "docs/program/annex-d-legacy-mapping.md",
  note: "Generated by scripts/build-legacy-crosswalk.mjs. Do not edit by hand.",
  verifyExtend,
  consolidations,
  aliases,
  crosswalk,
  plantModule,
  workchatModule,
};

writeFileSync(join(root, "src/program/legacy.generated.json"), JSON.stringify(out, null, 2) + "\n");
console.log(
  `Wrote ${crosswalk.length} crosswalk rows, ${verifyExtend.length} VERIFY & EXTEND Parts, ${consolidations.length} consolidations, ${aliases.length} alias rows, ${plantModule.length} plant and ${workchatModule.length} WorkChat module rows.`,
);
