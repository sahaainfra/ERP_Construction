// Generates src/program/parts.generated.json from docs/erp-program/annexes/annex-c-master-index.md (Part 00 Annex C2).
// Run with: node scripts/build-program-index.mjs
// Fails if the table cannot be parsed or a row is malformed, so the generated data never silently drifts.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const markdown = readFileSync(join(root, "docs/erp-program/annexes/annex-c-master-index.md"), "utf8");

const PART_ID = /^\d{2}[A-C]?$/;

// Returns the data rows of the table that follows a "## <heading>" line.
function tableRows(heading) {
  const lines = markdown.split("\n");
  const start = lines.findIndex((l) => l.startsWith(heading));
  if (start < 0) throw new Error(`Heading not found: ${heading}`);
  const rows = [];
  let seenSeparator = false;
  for (let i = start + 1; i < lines.length; i++) {
    const line = lines[i];
    if (line.startsWith("## ")) break;
    if (!line.startsWith("|")) continue;
    if (!seenSeparator) {
      seenSeparator = true; // header row, then |---| separator
      continue;
    }
    if (/^\|\s*-+/.test(line)) continue;
    rows.push({ line: i + 1, cells: line.slice(1, -1).split("|").map((c) => c.trim()) });
  }
  return rows;
}

const dash = (v) => (v === "—" || v === "" ? [] : v.split(",").map((x) => x.trim()).filter(Boolean));

// Lists written with a trailing "…" are truncated in the annex. Keep the visible IDs and flag the list.
function partList(cell) {
  const truncated = cell.includes("…");
  const ids = dash(cell.replace("…", "").trim());
  for (const id of ids) {
    if (!PART_ID.test(id)) throw new Error(`Unexpected part id "${id}" in "${cell}"`);
  }
  return { ids, truncated };
}

// C1: phase ranges
const phases = tableRows("## C1 Phases").map(({ line, cells }) => {
  const [phase, name, range, count] = cells;
  const match = range.match(/^(\d{2})–(\d{2})$/);
  if (!match) throw new Error(`Line ${line}: bad phase range "${range}"`);
  return { phase: Number(phase), name, first: match[1], last: match[2], count: Number(count) };
});

// C2: Part index. The header row for C2 is consumed by tableRows; rows must have 9 cells.
const parts = tableRows("## C2 Index").map(({ line, cells }) => {
  if (cells.length !== 9) throw new Error(`Line ${line}: expected 9 cells, got ${cells.length}`);
  const [id, title, code, phase, risk, mode, dependsOn, consumedBy, parallel] = cells;
  if (!PART_ID.test(id)) throw new Error(`Line ${line}: bad Part id "${id}"`);
  const deps = partList(dependsOn);
  const consumers = partList(consumedBy);
  const par = partList(parallel);
  return {
    id,
    title,
    code: code.replace(/`/g, ""),
    phase: Number(phase),
    risk,
    defaultMode: mode,
    dependsOn: deps.ids,
    consumedBy: consumers.ids,
    consumedByTruncated: consumers.truncated,
    parallelWith: par.ids,
  };
});

const seen = new Set();
for (const p of parts) {
  if (seen.has(p.id)) throw new Error(`Duplicate Part ${p.id}`);
  seen.add(p.id);
}

const out = {
  source: "docs/erp-program/annexes/annex-c-master-index.md",
  note: "Generated by scripts/build-program-index.mjs. Do not edit by hand.",
  phases,
  parts,
};

writeFileSync(join(root, "src/program/parts.generated.json"), JSON.stringify(out, null, 2) + "\n");
console.log(`Wrote ${parts.length} Parts across ${phases.length} phases.`);
