// Vendors the UI fonts into the repository (Part 12 REQ-DS-F02; A-74). Run once when a font version changes:
//   node scripts/design/vendor-fonts.mjs
// Downloads each family's woff2 subsets from the font host's stylesheet, writes public/fonts/<family>/*.woff2, writes
// src/design/fonts.css with local URLs and the original unicode ranges, and copies the OFL licence text. No runtime call to a third party.
import { mkdirSync, writeFileSync, readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "../..");
const UA = "Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0 Safari/537.36";
const FAMILIES = [
  { name: "IBM Plex Sans", slug: "ibm-plex-sans", query: "IBM+Plex+Sans:wght@400;500;600", licence: "https://raw.githubusercontent.com/google/fonts/main/ofl/ibmplexsans/OFL.txt" },
  { name: "IBM Plex Mono", slug: "ibm-plex-mono", query: "IBM+Plex+Mono:wght@400", licence: "https://raw.githubusercontent.com/google/fonts/main/ofl/ibmplexmono/OFL.txt" },
  { name: "Noto Sans Devanagari", slug: "noto-sans-devanagari", query: "Noto+Sans+Devanagari:wght@400;500", licence: "https://raw.githubusercontent.com/google/fonts/main/ofl/notosansdevanagari/OFL.txt" },
];

const blocks = [];
for (const family of FAMILIES) {
  const css = await (await fetch(`https://fonts.googleapis.com/css2?family=${family.query}&display=swap`, { headers: { "User-Agent": UA } })).text();
  const dir = join(root, "public/fonts", family.slug);
  mkdirSync(dir, { recursive: true });
  const faces = [...css.matchAll(/\/\*\s*([\w-]+)\s*\*\/\s*@font-face\s*{([^}]*)}/g)];
  if (faces.length === 0) throw new Error(`no font faces returned for ${family.name}`);
  for (const [, subset, body] of faces) {
    const weight = /font-weight:\s*(\d+)/.exec(body)[1];
    const url = /url\((https:[^)]+)\)/.exec(body)[1];
    const range = /unicode-range:\s*([^;]+);/.exec(body)[1];
    const file = `${subset}-${weight}.woff2`;
    const bytes = Buffer.from(await (await fetch(url)).arrayBuffer());
    writeFileSync(join(dir, file), bytes);
    blocks.push(`@font-face {\n  font-family: "${family.name}";\n  font-style: normal;\n  font-weight: ${weight};\n  font-display: swap;\n  src: url("/fonts/${family.slug}/${file}") format("woff2");\n  unicode-range: ${range};\n}`);
  }
  writeFileSync(join(dir, "OFL.txt"), await (await fetch(family.licence)).text());
  console.log(`${family.name}: ${faces.length} faces`);
}
writeFileSync(join(root, "src/design/fonts.css"), `/* GENERATED by scripts/design/vendor-fonts.mjs. Do not edit by hand. Files are in public/fonts (OFL, see OFL.txt in each folder). */\n\n${blocks.join("\n\n")}\n`);
console.log(`Wrote src/design/fonts.css (${blocks.length} faces)`);
