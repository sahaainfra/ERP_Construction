// Generates src/program/prompts.generated.json from docs/program/annex-e-session-prompts.md (Part 00 Annex E).
// Each fenced block under a heading "E<n>" (or "E1-legacy") becomes one template.
// Run with: node scripts/build-session-prompts.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const lines = readFileSync(join(root, "docs/program/annex-e-session-prompts.md"), "utf8").split("\n");

const templates = [];
let heading = null;
let block = null;

for (const line of lines) {
  if (block === null && /^#{2,3} /.test(line)) {
    heading = line.replace(/^#+ /, "");
    continue;
  }
  if (block === null && line.startsWith("```")) {
    block = [];
    continue;
  }
  if (block !== null && line.startsWith("```")) {
    const match = heading.match(/^(E\d+(?:-legacy)?)\b/);
    if (!match) throw new Error(`Code block under unexpected heading: ${heading}`);
    templates.push({ id: match[1], heading, text: block.join("\n") });
    block = null;
    continue;
  }
  if (block !== null) block.push(line);
}

if (block !== null) throw new Error("Unterminated code block");
const ids = templates.map((t) => t.id);
if (new Set(ids).size !== ids.length) throw new Error(`Duplicate template ids: ${ids.join(", ")}`);

writeFileSync(
  join(root, "src/program/prompts.generated.json"),
  JSON.stringify({ source: "docs/program/annex-e-session-prompts.md", note: "Generated by scripts/build-session-prompts.mjs. Do not edit by hand.", templates }, null, 2) + "\n",
);
console.log(`Wrote ${templates.length} templates: ${ids.join(", ")}`);
